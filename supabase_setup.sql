-- 1. جدول المنتجات
-- =====================================================
CREATE TABLE IF NOT EXISTS public.products (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name_ar     TEXT NOT NULL,
  name_fr     TEXT NOT NULL,
  description_ar TEXT NOT NULL,
  description_fr TEXT NOT NULL,
  price       NUMERIC NOT NULL,
  rating      NUMERIC DEFAULT 5,
  category    TEXT NOT NULL CHECK (category IN ('kitchen', 'decor', 'appliances')),
  image       TEXT NOT NULL,
  is_featured BOOLEAN DEFAULT false,
  in_stock    BOOLEAN DEFAULT true,
  created_at  TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public read products" ON public.products;
DROP POLICY IF EXISTS "Allow public insert products" ON public.products;
DROP POLICY IF EXISTS "Allow public update products" ON public.products;
DROP POLICY IF EXISTS "Allow public delete products" ON public.products;

CREATE POLICY "Allow public read products"   ON public.products FOR SELECT USING (true);
CREATE POLICY "Allow public insert products" ON public.products FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update products" ON public.products FOR UPDATE USING (true);
CREATE POLICY "Allow public delete products" ON public.products FOR DELETE USING (true);


-- 2. جدول الطلبات (جديد)
-- =====================================================
CREATE TABLE IF NOT EXISTS public.orders (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_name    TEXT NOT NULL,
  customer_phone   TEXT NOT NULL,
  customer_address TEXT NOT NULL,
  items            JSONB NOT NULL,
  total            NUMERIC NOT NULL,
  status           TEXT DEFAULT 'pending'
                   CHECK (status IN ('pending','confirmed','processing','delivered','cancelled')),
  notes            TEXT,
  created_at       TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public insert orders" ON public.orders;
DROP POLICY IF EXISTS "Allow admin read orders"   ON public.orders;
DROP POLICY IF EXISTS "Allow admin update orders" ON public.orders;

CREATE POLICY "Allow public insert orders" ON public.orders FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow admin read orders"   ON public.orders FOR SELECT USING (true);
CREATE POLICY "Allow admin update orders" ON public.orders FOR UPDATE USING (true);


